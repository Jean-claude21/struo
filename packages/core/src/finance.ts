/** The company's money at a glance (dashboard). */
export async function financeSummary(db: Db, actor: Actor) {
  return asActor(db, actor, async (tx) => {
    const { rows } = await tx.query(
      `select coalesce(sum(f.budget_minor), 0)::bigint as "budgetMinor",
              coalesce(sum(f.invoiced_minor), 0)::bigint as "invoicedMinor",
              coalesce(sum(f.collected_minor), 0)::bigint as "collectedMinor",
              coalesce(sum(f.invoiced_net_minor - f.collected_minor), 0)::bigint as "receivableMinor",
              coalesce(sum(f.retention_minor), 0)::bigint as "retentionMinor",
              coalesce(sum(f.spent_minor), 0)::bigint as "spentMinor",
              coalesce(sum(f.overdue_minor), 0)::bigint as "overdueMinor",
              coalesce(sum(f.cash_minor), 0)::bigint as "cashMinor",
              -- collected out of what was invoiced (the same rate as the finance page)
              case when sum(f.invoiced_net_minor) > 0 then round(sum(f.collected_minor)::numeric * 100 / sum(f.invoiced_net_minor))::int else 0 end
                as "collectedPct",
              case when sum(f.collected_minor) > 0
                   then round((sum(f.collected_minor) - sum(f.spent_minor))::numeric * 100 / sum(f.collected_minor))::int
                   else null end as "marginPct",
              -- margin expected at completion: the cost so far, projected from the progress of each open site
              case when sum(f.budget_minor) filter (where p.status in ('active', 'suspended') and f.progress_pct > 0) > 0
                   then round((sum(f.budget_minor) filter (where p.status in ('active', 'suspended') and f.progress_pct > 0)
                               - sum(f.spent_minor * 100.0 / f.progress_pct) filter (where p.status in ('active', 'suspended') and f.progress_pct > 0))
                              * 100 / sum(f.budget_minor) filter (where p.status in ('active', 'suspended') and f.progress_pct > 0))::int
                   else null end as "projectedMarginPct",
              (select coalesce(sum(b.balance_minor), 0) from invoice_balance b join invoice i on i.id = b.invoice_id
                where b.org_id = $1 and i.status = 'issued' and b.balance_minor > 0 and b.due_on between current_date and current_date + 30)::bigint
                as "dueSoonMinor"
         from project_finance f join project p on p.id = f.project_id
        where f.org_id = $1 and p.archived_at is null`,
      [actor.orgId],
    );
    const row = rows[0];
    return {
      ...row,
      budgetMinor: Number(row.budgetMinor), invoicedMinor: Number(row.invoicedMinor), collectedMinor: Number(row.collectedMinor),
      receivableMinor: Number(row.receivableMinor), retentionMinor: Number(row.retentionMinor), spentMinor: Number(row.spentMinor),
      overdueMinor: Number(row.overdueMinor), cashMinor: Number(row.cashMinor), dueSoonMinor: Number(row.dueSoonMinor),
    } as {
      budgetMinor: number; invoicedMinor: number; collectedMinor: number; receivableMinor: number; retentionMinor: number;
      spentMinor: number; overdueMinor: number; cashMinor: number; collectedPct: number; marginPct: number | null;
      projectedMarginPct: number | null; dueSoonMinor: number;
    };
  });
}

export interface ProgressStatement {
  projectId: string;
  currencyCode: string;
  phases: { name: string; budgetMinor: number; progressPct: number; earnedMinor: number }[];
  earnedMinor: number;
  invoicedMinor: number;
  /** Excl. tax: what the validated progress allows to invoice now. */
  suggestedMinor: number;
  advanceMinor: number;
  advanceDeductedMinor: number;
  /** Share of the remaining advance to deduct, in proportion of this statement to the budget. */
  suggestedDeductionMinor: number;
  nextNumber: number;
}

/**
 * The next progress statement of a site (spec 026): each phase's budget times its validated
 * progress, minus what progress and final invoices already billed (excl. tax). The advance is
 * deducted in proportion. Figures only from the database: nothing typed by hand.
 */
export async function progressStatement(db: Db, actor: Actor, projectId: string): Promise<ProgressStatement> {
  ensure(actor, 'finance.write');
  return asActor(db, actor, async (tx) => {
    const project = (await tx.query<{ budget_minor: number; currency_code: string }>(
      'select budget_minor, currency_code from project where id = $1 and org_id = $2', [projectId, actor.orgId])).rows[0];
    if (!project) throw notFound();
    const phases = (await tx.query<{ name: string; budget: number; progress: number }>(
      'select name, budget_minor as budget, progress_pct as progress from project_phase where project_id = $1 order by position, name', [projectId])).rows;
    const totals = (await tx.query<{ invoiced: number; advance: number; deducted: number; statements: number }>(
      `select coalesce(sum(amount_minor) filter (where kind in ('progress', 'final')), 0)::bigint as invoiced,
              coalesce(sum(amount_minor) filter (where kind = 'advance'), 0)::bigint as advance,
              coalesce(sum(deduction_minor), 0)::bigint as deducted,
              count(*) filter (where kind = 'progress')::int as statements
         from invoice where project_id = $1 and org_id = $2 and status = 'issued'`, [projectId, actor.orgId])).rows[0]!;
    const rows = phases.map((phase) => ({
      name: phase.name, budgetMinor: Number(phase.budget), progressPct: phase.progress, earnedMinor: Math.round((Number(phase.budget) * phase.progress) / 100),
    }));
    const earned = rows.reduce((sum, row) => sum + row.earnedMinor, 0);
    const invoiced = Number(totals.invoiced);
    const suggested = Math.max(0, earned - invoiced);
    const advance = Number(totals.advance);
    const deducted = Number(totals.deducted);
    const budget = Number(project.budget_minor) || earned || 1;
    const deduction = Math.min(Math.max(0, advance - deducted), Math.round((advance * suggested) / budget));
    return {
      projectId, currencyCode: project.currency_code, phases: rows, earnedMinor: earned, invoicedMinor: invoiced, suggestedMinor: suggested,
      advanceMinor: advance, advanceDeductedMinor: deducted, suggestedDeductionMinor: deduction, nextNumber: Number(totals.statements) + 1,
    };
  });
}
