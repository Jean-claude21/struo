#!/usr/bin/env node
// Provisions and deploys an environment of Struo: Neon project and branch, generated secrets,
// Coolify project, application (image published by the CI on GHCR), variables, deployment, health.
//   node scripts/deploy.mjs --env staging     (Neon branch dev,  image tag dev)
//   node scripts/deploy.mjs --env production  (Neon branch main, image tag latest)
// Secrets are read from files outside the repository and NEVER printed (constitution):
//   STRUO_ADMIN_SECRETS (default ../.secrets/.admin.env): NEON_API_TOKEN, COOLIFY_URL, COOLIFY_API_TOKEN
//   STRUO_SECRETS (default ../.secrets/struo.env): generated values of this project (written by this script)
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { parseArgs } from 'node:util';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { values: args } = parseArgs({ options: { env: { type: 'string', default: 'staging' }, 'no-deploy': { type: 'boolean' }, seed: { type: 'boolean' } } });
if (args.seed && args.env !== 'staging') throw new Error('--seed only fills staging with fictional demo data');
const TARGETS = {
  staging: { branch: 'dev', tag: 'dev', app: 'struo-staging', environment: 'staging' },
  production: { branch: 'main', tag: 'latest', app: 'struo', environment: 'production' },
};
const target = TARGETS[args.env];
if (!target) throw new Error(`Unknown environment: ${args.env}`);
const ENV = args.env.toUpperCase();

const ADMIN = process.env.STRUO_ADMIN_SECRETS ?? path.resolve(ROOT, '../.secrets/.admin.env');
const OWN = process.env.STRUO_SECRETS ?? path.resolve(ROOT, '../.secrets/struo.env');
const unquote = (value) => (/^(["']).*\1$/su.test(value) ? value.slice(1, -1) : value);
const readEnv = (file) =>
  existsSync(file)
    ? Object.fromEntries(
        readFileSync(file, 'utf8')
          .split(/\r?\n/u)
          .filter((line) => /^[A-Z][A-Z0-9_]*=/u.test(line))
          .map((line) => [line.slice(0, line.indexOf('=')), unquote(line.slice(line.indexOf('=') + 1).trim())]),
      )
    : {};
const admin = readEnv(ADMIN);
let own = readEnv(OWN);
const remember = (name, value) => {
  const text = existsSync(OWN) ? readFileSync(OWN, 'utf8') : '# Struo — generated by scripts/deploy.mjs. Never commit.\n';
  const pattern = new RegExp(`^${name}=.*$`, 'mu');
  writeFileSync(OWN, pattern.test(text) ? text.replace(pattern, `${name}=${value}`) : `${text.trimEnd()}\n${name}=${value}\n`);
  own = readEnv(OWN);
};
const secret = (name, make) => {
  if (!own[name]) {
    remember(name, make());
    console.log(`${name}: generated and stored`);
  }
  return own[name];
};
for (const name of ['NEON_API_TOKEN', 'COOLIFY_URL', 'COOLIFY_API_TOKEN']) {
  if (!admin[name]) throw new Error(`${name} is empty in ${ADMIN}.`);
}

const client = (base, token) => async (route, init = {}) => {
  const response = await fetch(`${base}${route}`, {
    ...init,
    headers: { Authorization: `Bearer ${token}`, Accept: 'application/json', 'Content-Type': 'application/json' },
  });
  const text = await response.text();
  if (!response.ok) throw new Error(`${init.method ?? 'GET'} ${route}: HTTP ${response.status} ${text.slice(0, 300)}`);
  return text ? JSON.parse(text) : {};
};
const neon = client('https://console.neon.tech/api/v2', admin.NEON_API_TOKEN);
const coolify = client(`${admin.COOLIFY_URL.replace(/\/$/u, '')}/api/v1`, admin.COOLIFY_API_TOKEN);
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

// ---------------------------------------------------------------- Neon
async function waitOperations(projectId) {
  for (let i = 0; i < 60; i += 1) {
    const { operations } = await neon(`/projects/${projectId}/operations?limit=10`);
    if (!operations.some((op) => ['running', 'scheduling'].includes(op.status))) return;
    await sleep(2000);
  }
}
let projectId = own.NEON_PROJECT_ID;
if (!projectId) {
  const { projects } = await neon('/projects?limit=100');
  projectId = projects.find((p) => p.name === 'struo')?.id;
  if (!projectId) {
    const created = await neon('/projects', {
      method: 'POST',
      body: JSON.stringify({ project: { name: 'struo', region_id: 'aws-eu-central-1', pg_version: 17 } }),
    });
    projectId = created.project.id;
    console.log('Neon: project « struo » created (Frankfurt, PostgreSQL 17)');
  }
  remember('NEON_PROJECT_ID', projectId);
}
await waitOperations(projectId);
let { branches } = await neon(`/projects/${projectId}/branches`);
const main = branches.find((b) => b.default) ?? branches.find((b) => b.name === 'main');
for (const name of ['dev', 'test']) {
  if (!branches.some((b) => b.name === name)) {
    await neon(`/projects/${projectId}/branches`, {
      method: 'POST',
      body: JSON.stringify({ branch: { name, parent_id: main.id }, endpoints: [{ type: 'read_write' }] }),
    });
    console.log(`Neon: branch « ${name} » created`);
    await waitOperations(projectId);
  }
}
({ branches } = await neon(`/projects/${projectId}/branches`));
const branch = target.branch === 'main' ? main : branches.find((b) => b.name === target.branch);
const { roles } = await neon(`/projects/${projectId}/branches/${branch.id}/roles`);
const ownerRole = roles.find((r) => r.name !== 'struo_app' && !r.protected)?.name ?? 'neondb_owner';
const { databases } = await neon(`/projects/${projectId}/branches/${branch.id}/databases`);
const database = databases[0]?.name ?? 'neondb';
const { uri: ownerUrl } = await neon(
  `/projects/${projectId}/connection_uri?branch_id=${branch.id}&database_name=${database}&role_name=${ownerRole}&pooled=false`,
);
const appPassword = secret(`APP_DB_PASSWORD_${ENV}`, () => randomBytes(24).toString('base64url'));
const appUrl = (() => {
  const url = new URL(ownerUrl);
  url.username = 'struo_app';
  url.password = appPassword;
  return url.toString();
})();
console.log(`Neon: branch « ${branch.name} » ready`);

// ---------------------------------------------------------------- Neon object storage (files)
// The branch's own storage, a scoped credential and a `files` bucket (pattern of Jarvis' provision).
const storageState = await neon(`/projects/${projectId}/branches/${branch.id}/storage`).catch(() => null);
let storageVariables = {};
if (storageState?.s3_endpoint) {
  if (!own[`S3_ACCESS_KEY_ID_${ENV}`] || !own[`S3_SECRET_ACCESS_KEY_${ENV}`]) {
    const credential = await neon(`/projects/${projectId}/branches/${branch.id}/credentials`, {
      method: 'POST',
      body: JSON.stringify({ scopes: ['storage:read', 'storage:write'], principal_type: 'user', name: `struo-${args.env}` }),
    });
    remember(`S3_ACCESS_KEY_ID_${ENV}`, credential.token_id);
    remember(`S3_SECRET_ACCESS_KEY_${ENV}`, credential.s3_secret_access_key);
    console.log(`Neon storage: credential created for ${args.env}`);
  }
  const require = createRequire(path.join(ROOT, 'apps/web/package.json'));
  const { S3Client, HeadBucketCommand, CreateBucketCommand } = require('@aws-sdk/client-s3');
  const s3 = new S3Client({
    region: storageState.region,
    endpoint: storageState.s3_endpoint,
    forcePathStyle: true,
    credentials: { accessKeyId: own[`S3_ACCESS_KEY_ID_${ENV}`], secretAccessKey: own[`S3_SECRET_ACCESS_KEY_${ENV}`] },
  });
  try {
    await s3.send(new HeadBucketCommand({ Bucket: 'files' }));
  } catch {
    await s3.send(new CreateBucketCommand({ Bucket: 'files' }));
    console.log('Neon storage: bucket « files » created');
  }
  storageVariables = {
    S3_ENDPOINT: storageState.s3_endpoint,
    S3_REGION: storageState.region,
    S3_BUCKET: 'files',
    S3_ACCESS_KEY_ID: own[`S3_ACCESS_KEY_ID_${ENV}`],
    S3_SECRET_ACCESS_KEY: own[`S3_SECRET_ACCESS_KEY_${ENV}`],
  };
} else {
  console.log('Neon storage: not available on this branch — files stay on the container volume.');
}

// ---------------------------------------------------------------- Coolify
const projects = await coolify('/projects');
let project = projects.find((p) => p.name === 'Struo');
if (!project) {
  project = await coolify('/projects', { method: 'POST', body: JSON.stringify({ name: 'Struo', description: 'Struo - gestion de chantiers BTP' }) });
  console.log('Coolify: project « Struo » created');
}
const detail = await coolify(`/projects/${project.uuid}`);
if (!(detail.environments ?? []).some((e) => e.name === target.environment)) {
  await coolify(`/projects/${project.uuid}/environments`, { method: 'POST', body: JSON.stringify({ name: target.environment }) });
  console.log(`Coolify: environment « ${target.environment} » created`);
}
const servers = await coolify('/servers');
const server = servers.find((s) => s.uuid === own.COOLIFY_SERVER_UUID) ?? servers[0];
if (!server) throw new Error('No Coolify server.');
const domain = (own[`DOMAIN_${ENV}`] || `https://${target.app}.${server.ip}.sslip.io`).replace(/\/$/u, '');
const image = 'ghcr.io/jean-claude21/struo';
let application = (await coolify('/applications')).find((a) => a.name === target.app);
if (!application) {
  application = await coolify('/applications/dockerimage', {
    method: 'POST',
    body: JSON.stringify({
      project_uuid: project.uuid,
      server_uuid: server.uuid,
      environment_name: target.environment,
      name: target.app,
      description: `Struo - ${args.env}`,
      docker_registry_image_name: image,
      docker_registry_image_tag: target.tag,
      ports_exposes: '3000',
      domains: domain,
      health_check_enabled: true,
      health_check_path: '/api/health',
      health_check_port: '3000',
      health_check_host: '127.0.0.1',
      instant_deploy: false,
    }),
  });
  console.log(`Coolify: application « ${target.app} » created`);
} else {
  await coolify(`/applications/${application.uuid}`, {
    method: 'PATCH',
    body: JSON.stringify({ docker_registry_image_tag: target.tag, domains: domain }),
  });
}
remember(`COOLIFY_APP_UUID_${ENV}`, application.uuid);

const variables = {
  APP_ENV: 'production',
  APP_BASE_URL: domain,
  DATABASE_URL: appUrl,
  DATABASE_OWNER_URL: ownerUrl,
  APP_DB_PASSWORD: appPassword,
  BETTER_AUTH_SECRET: secret(`BETTER_AUTH_SECRET_${ENV}`, () => randomBytes(48).toString('base64url')),
  SECRETS_KEY: secret(`SECRETS_KEY_${ENV}`, () => randomBytes(32).toString('base64')),
  PLATFORM_ADMIN_EMAILS: own.PLATFORM_ADMIN_EMAILS ?? '',
  STORAGE_DIR: '/data/storage',
  JOBS_ENABLED: 'true',
  // The staging instance is a demo: the payment simulator is allowed there, never in production.
  PAYMENTS_SIMULATOR: args.env === 'staging' ? 'true' : 'false',
  ...storageVariables,
  ...((admin.RESEND_API_KEY ?? own.RESEND_API_KEY) ? { RESEND_API_KEY: admin.RESEND_API_KEY ?? own.RESEND_API_KEY } : {}),
  ...(own.MAIL_FROM ? { MAIL_FROM: own.MAIL_FROM } : {}),
  ...(admin.OPENAI_API_KEY ? { OPENAI_API_KEY: admin.OPENAI_API_KEY } : {}),
  // Struo Intelligence (spec 034): the assistant's model, and Sign in with ChatGPT once OpenAI issues the client.
  ...(own.OPENAI_AGENT_MODEL ? { OPENAI_AGENT_MODEL: own.OPENAI_AGENT_MODEL } : {}),
  ...(own.OPENAI_SIWC_CLIENT_ID ? { OPENAI_SIWC_CLIENT_ID: own.OPENAI_SIWC_CLIENT_ID } : {}),
  ...(own.OPENAI_SIWC_CLIENT_SECRET ? { OPENAI_SIWC_CLIENT_SECRET: own.OPENAI_SIWC_CLIENT_SECRET } : {}),
  // Subscriptions sold as licences on Chariow (spec 038).
  ...(own.CHARIOW_API_KEY ? { CHARIOW_API_KEY: own.CHARIOW_API_KEY } : {}),
  // Monitoring (spec 041): errors from both environments; audience analytics in production only,
  // so tests on staging never count as visits.
  ...(own.SENTRY_DSN ? { SENTRY_DSN: own.SENTRY_DSN } : {}),
  ...(args.env === 'production' && own.UMAMI_WEBSITE_ID && own.UMAMI_SCRIPT_URL ? { UMAMI_WEBSITE_ID: own.UMAMI_WEBSITE_ID, UMAMI_SCRIPT_URL: own.UMAMI_SCRIPT_URL } : {}),
};
await coolify(`/applications/${application.uuid}/envs/bulk`, {
  method: 'PATCH',
  body: JSON.stringify({
    data: Object.entries(variables).map(([key, value]) => ({ key, value: String(value), is_preview: false, is_literal: true })),
  }),
});
console.log(`Coolify: ${Object.keys(variables).length} variables set (${Object.keys(variables).join(', ')})`);

// Persistent storage for uploaded files (until object storage is configured).
try {
  await coolify(`/applications/${application.uuid}/storages`, {
    method: 'POST',
    body: JSON.stringify({ name: `${target.app}-files`, mount_path: '/data/storage' }),
  });
} catch {
  /* already there, or not supported by this Coolify version */
}

if (!args['no-deploy']) {
  // A restart recreates the container with the variables just written; a « deploy » of the same
  // image is skipped by Coolify and would leave the old variables running.
  const restart = await coolify(`/applications/${application.uuid}/restart`, { method: 'POST' });
  console.log(`Coolify: restart requested → ${domain}`);
  const deployment = restart?.deployment_uuid;
  for (let i = 0; deployment && i < 60; i += 1) {
    await sleep(10_000);
    const state = await coolify(`/deployments/${deployment}`).catch(() => null);
    if (state?.status === 'finished') break;
    if (state?.status === 'failed' || state?.status === 'cancelled-by-user') { console.log(`Coolify: restart ${state.status}`); process.exit(1); }
  }
  for (let i = 0; i < 60; i += 1) {
    await sleep(10_000);
    try {
      const response = await fetch(`${domain}/api/health`);
      if (response.ok) {
        console.log(`Healthy: ${domain}/api/health`);
        if (args.seed) seedDemo(storageVariables);
        process.exit(0);
      }
    } catch {
      /* not up yet */
    }
  }
  console.log('Not healthy after 10 minutes: check the Coolify logs.');
  process.exit(1);
}

/** Fictional demo company on staging (apps/web/scripts/seed.ts), password kept in the project secrets. */
function seedDemo(storage = {}) {
  const password = secret('DEMO_PASSWORD_STAGING', () => `demo-${randomBytes(6).toString('hex')}`);
  const result = spawnSync('pnpm', ['exec', 'tsx', 'scripts/seed.ts'], {
    cwd: path.join(ROOT, 'apps/web'), stdio: 'inherit', shell: process.platform === 'win32',
    // The demo photos go to the same storage as the app's files.
    env: { ...process.env, ...storage, DATABASE_URL: appUrl, DATABASE_OWNER_URL: ownerUrl, SEED_PASSWORD: password, NODE_ENV: 'staging', APP_BASE_URL: domain },
  });
  console.log(result.status === 0 ? 'Demo data seeded (accounts: demo@, jean@, komi@, akossiwa@struo.test; password DEMO_PASSWORD_STAGING)' : 'Demo seed failed');
}
